export const locales = ['zh', 'en', 'ja'] as const;
export type Locale = (typeof locales)[number];
export const defaultLocale: Locale = 'zh';

export const localeMeta: Record<Locale, { label: string; htmlLang: string; ogLocale: string; prefix: string }> = {
  zh: { label: '中文', htmlLang: 'zh-Hans', ogLocale: 'zh_CN', prefix: '' },
  en: { label: 'EN', htmlLang: 'en', ogLocale: 'en_US', prefix: '/en' },
  ja: { label: '日本語', htmlLang: 'ja', ogLocale: 'ja_JP', prefix: '/ja' },
};

export function localePath(locale: Locale, path: string) {
  const clean = path.startsWith('/') ? path : `/${path}`;
  if (locale === 'zh') return clean;
  return `${localeMeta[locale].prefix}${clean === '/' ? '/' : clean}`;
}

export function alternatePaths(path: string) {
  return Object.fromEntries(locales.map((locale) => [locale, localePath(locale, path)])) as Record<Locale, string>;
}

